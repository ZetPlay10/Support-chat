-- Schema initiala, conform diagramei ER din docs/diagrame.md

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'AGENT', 'ADMIN')),
    online        BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE conversations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject    VARCHAR(200) NOT NULL,
    status     VARCHAR(20)  NOT NULL DEFAULT 'WAITING' CHECK (status IN ('WAITING', 'ACTIVE', 'CLOSED')),
    client_id  BIGINT       NOT NULL REFERENCES users (id),
    agent_id   BIGINT       REFERENCES users (id),          -- null cat timp e in asteptare
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at  TIMESTAMP
);

CREATE INDEX idx_conversations_client ON conversations (client_id);
CREATE INDEX idx_conversations_agent ON conversations (agent_id);
CREATE INDEX idx_conversations_status ON conversations (status);

CREATE TABLE messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT    NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    sender_id       BIGINT    NOT NULL REFERENCES users (id),
    content         TEXT      NOT NULL,
    sent_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_read         BOOLEAN   NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_messages_conversation ON messages (conversation_id, sent_at);
